import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const source = JSON.parse(readFileSync(new URL('../src/tokens/foundations.tokens.json', import.meta.url), 'utf8'));
export function cssValue(token) {
  const v = token.$value;
  switch (token.$type) {
    case 'color':
      assert.equal(v.colorSpace, 'srgb');
      assert.equal(v.alpha, 1);
      assert.equal(v.components.length, 3);
      assert(v.components.every(n => Number.isFinite(n) && n >= 0 && n <= 1));
      return '#' + v.components.map(n => Math.round(n * 255).toString(16).padStart(2, '0')).join('');
    case 'dimension':
    case 'duration':
      assert(Number.isFinite(v.value));
      assert((token.$type === 'dimension' ? ['px', 'rem'] : ['ms', 's']).includes(v.unit));
      return `${v.value}${v.unit}`;
    case 'number': assert(Number.isFinite(v)); return String(v);
    case 'fontFamily':
      assert(Array.isArray(v) && v.every(x => typeof x === 'string' && x.length > 0));
      return v.map(x => /\s/.test(x) ? JSON.stringify(x) : x).join(', ');
    case 'cubicBezier':
      assert(Array.isArray(v) && v.length === 4 && v.every(Number.isFinite));
      assert(v[0] >= 0 && v[0] <= 1 && v[2] >= 0 && v[2] <= 1);
      return `cubic-bezier(${v.join(', ')})`;
    default: throw new Error(`Tipo não suportado: ${token.$type}`);
  }
}
export function declarations(group) {
  const values = {};
  for (const [name, token] of Object.entries(group)) {
    if (name.startsWith('$')) continue;
    assert(token.$description && typeof token.$deprecated === 'boolean', `Metadados: ${name}`);
    values[`--${name}`] = cssValue(token);
  }
  for (const [name, entry] of Object.entries(group.$extensions['org.refy.css'])) {
    assert(/^--[\w-]+$/.test(name) && typeof entry.value === 'string' && entry.description);
    values[name] = entry.value;
  }
  return values;
}
export function themeValues(mode) {
  assert(['light', 'dark', 'editorial'].includes(mode), `Modo inválido: ${mode}`);
  return { ...declarations(source.base), ...declarations(source[mode]) };
}
export function generateCSS() {
  const block = (selector, values) => `${selector} {\n${Object.entries(values).sort(([a], [b]) => a.localeCompare(b, 'en')).map(([key, value]) => `  ${key}: ${value};`).join('\n')}\n}\n`;
  // Só a raiz (o documento, o provider de fora ou um provider com isolate) recebe a fundação inteira.
  // Um provider aninhado herda o que o pai calculou e redeclara só os aliases; trocando de modo,
  // recebe também os tokens do modo, que precisam resolver na paleta nova.
  const root = ':where([data-refy-root])';
  const standalone = ':not([data-refy-scope])';
  const nested = '[data-refy-scope]:not([data-refy-root])';
  const switched = `${nested}[data-refy-mode-switch]`;
  const aliases = values => Object.fromEntries(Object.entries(values).filter(([, value]) => value.includes('var(')));
  const baseAliases = aliases(declarations(source.base));
  const scheme = mode => mode === 'dark' ? 'dark' : 'light';
  return '/* Generated by npm run tokens:build. Edit foundations.tokens.json. */\n' +
    block(`:root, ${root}, [data-theme="light"]${standalone}`, { ...themeValues('light'), 'color-scheme': 'light' }) +
    ['dark', 'editorial'].map(mode => block(`${root}[data-theme="${mode}"], [data-theme="${mode}"]${standalone}`, { ...themeValues(mode), 'color-scheme': scheme(mode) })).join('\n') +
    // Um alias calculado no pai chega pronto ao filho; redeclarado aqui, ele resolve com os tokens
    // que o tema aninhado troca (ex.: --field-radius segue o --control-radius do aninhado).
    '\n' + ['light', 'dark', 'editorial'].map(mode => block(`${nested}[data-theme="${mode}"]`, aliases(themeValues(mode)))).join('\n') +
    '\n' + ['light', 'dark', 'editorial'].map(mode => block(`${switched}[data-theme="${mode}"]`, { ...baseAliases, ...declarations(source[mode]), 'color-scheme': scheme(mode) })).join('\n') +
    // Component hooks have no foundation value: without this reset a root scope inside another page
    // inherits the value the outer theme computed (e.g. Refy's green inside a dark theme).
    '\n' + block(root, Object.fromEntries(componentHooks().map(name => [name, 'initial'])));
}
export function componentHooks() {
  const hooks = JSON.parse(readFileSync(new URL('../src/tokens/component-hooks.json', import.meta.url), 'utf8'));
  return hooks.filter(name => !Object.hasOwn(themeValues('light'), name));
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../src/tokens/tokens.css', import.meta.url), generateCSS());
  console.log('OK: tokens.css gerado a partir da fonte estruturada.');
}
